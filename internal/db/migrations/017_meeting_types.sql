-- 017：事件类型加「算见面」开关
--
-- 背景：往来里除了见面（见面聊天、一起吃饭），还会记电话微信、纯送礼这类
-- 不见面的活动。「见面间隔」「上次见面」只该统计真正到场的往来，否则一个
-- 电话就会把间隔重置，数字失去参考意义。
--
-- 口径：默认 1（算见面）——大多数往来确实是见面的，电话微信这类少数类型
-- 由用户在设置里关掉；没有类型的往来（type_id 为空）一律算见面，删除
-- 事件类型会把往来置回未分类，正好也落回这个默认。
ALTER TABLE event_types ADD COLUMN is_meeting INTEGER NOT NULL DEFAULT 1;
